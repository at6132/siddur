/** Get one-line parsha summary; pass English parsha name (e.g. "Bereshit"). */
export function getParshaSummary(parshaName: string | undefined): string {
  if (!parshaName) return 'This week\'s Torah portion.';
  const normalized = parshaName.replace(/^Parashat\s+/i, '').trim();
  return PARSHA_SUMMARIES[normalized] || `${parshaName} — see the full parsha in the Library.`;
}
