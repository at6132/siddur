/**
 * Static content for home screen learning widgets.
 * 100-day cycle: same content repeats every 100 days so users don't see duplicates for 100 days.
 */

const EPOCH_MS = new Date(2020, 0, 1).getTime();
const MS_PER_DAY = 86400000;

/** Returns 0..99 for a 100-day cycle (same index for 100 days, then repeats). */
export function getIndex100(): number {
  const daysSince = Math.floor((Date.now() - EPOCH_MS) / MS_PER_DAY);
  return Math.abs(daysSince % 100);
}

/** Get content for today from an array; uses 100-day cycle so no duplicate for 100 days. */
export function getByDay100<T>(arr: T[]): T {
  const i = getIndex100() % arr.length;
  return arr[i];
}

